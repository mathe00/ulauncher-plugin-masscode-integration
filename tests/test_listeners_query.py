class TestApplySmartSingleResult:
    """Ratio-based reduction to a single result."""

    def test_dominant_snippet_collapses_to_single_result(self):
        history = {"q": {"alpha": 9, "beta": 1}}  # alpha ratio = 0.9

        result = listener_apply(history, "q", threshold=0.7)

        assert len(result) == 1
        assert result[0]["name"] == "alpha"

    def test_ratio_below_threshold_keeps_all(self):
        history = {"q": {"alpha": 5, "beta": 5}}  # alpha ratio = 0.5

        result = listener_apply(history, "q", threshold=0.7)

        assert len(result) == 2

    def test_unknown_query_history_requires_caller_guard(self):
        """
        QUIRK (pinned): _apply_smart_single_result indexes the history dict
        directly — it RAISES KeyError when the query has no history entry.
        Callers MUST pre-check `query in context_history` (on_event does).
        """
        with pytest.raises(KeyError):
            listener_apply({"other": {"x": 1}}, "q", threshold=0.1)

    def test_zero_total_selections_keeps_all(self):
        result = listener_apply({"q": {}}, "q", threshold=0.5)

        assert len(result) == 2

    def test_exact_threshold_boundary_passes(self):
        history = {"q": {"alpha": 1, "beta": 1}}  # alpha ratio = 0.5

        result = listener_apply(history, "q", threshold=0.5)

        assert len(result) == 1


def listener_apply(history, query, threshold):
    """Helper invoking _apply_smart_single_result with sensible matches."""
    listener = KeywordQueryEventListener()
    matches = [
        {"name": "alpha", "fuzzy_score": 90},
        {"name": "beta", "fuzzy_score": 80},
    ]
    return listener._apply_smart_single_result(
        matches=matches,
        query=query,
        context_history=history,
        smart_ratio_threshold=threshold,
    )


