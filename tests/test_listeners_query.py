class TestMatchSnippets:
    """Snippet→match transformation with fragments and context scores."""

    def make_listener(self):
        return KeywordQueryEventListener()

    def test_threshold_filters_weak_matches(self):
        listener = self.make_listener()
        snippets = [make_snippet(name="target snippet", content="xyz")]

        matches = listener._match_snippets(snippets, "totally-unrelated-zzz", {}, False)

        assert matches == []

    def test_no_query_returns_everything(self):
        listener = self.make_listener()
        snippets = [make_snippet(name=f"s{i}") for i in range(5)]

        matches = listener._match_snippets(snippets, "", {}, False)

        assert len(matches) == 5
        assert all(m["fuzzy_score"] == 100 for m in matches)

    def test_fragment_display_names_and_labels(self):
        listener = self.make_listener()
        snippets = [
            {
                "name": "multi",
                "content": [
                    {"label": "Frag A", "value": "aaa"},
                    {"label": "Frag B", "value": "bbb"},
                ],
            }
        ]

        matches = listener._match_snippets(snippets, "", {}, False)

        assert {m["name"] for m in matches} == {"multi [Frag A]", "multi [Frag B]"}
        assert {m["fragment_label"] for m in matches} == {"Frag A", "Frag B"}

    def test_context_score_computed_from_relevant_contexts(self):
        listener = self.make_listener()
        snippets = [make_snippet(name="docker ps", content="docker ps -a")]
        contexts = {
            "dock": {
                "snippets": {"docker ps": 3},
                "relevance": 1.0,
            }
        }

        matches = listener._match_snippets(
            snippets, "dock", contexts, contextual_learning_enabled=True
        )

        scored = next(m for m in matches if m["name"] == "docker ps")
        assert scored["context_score"] == int(3 * 1.0 * 100)

    def test_context_ignored_when_learning_disabled(self):
        listener = self.make_listener()
        snippets = [make_snippet(name="docker ps", content="docker ps")]
        contexts = {"dock": {"snippets": {"docker ps": 3}, "relevance": 1.0}}

        matches = listener._match_snippets(
            snippets, "dock", contexts, contextual_learning_enabled=False
        )

        assert all(m["context_score"] == 0 for m in matches)

    def test_match_payload_keys_complete(self):
        listener = self.make_listener()
        snippets = [make_snippet(name="simple", content="code")]

        matches = listener._match_snippets(snippets, "sim", {}, False)

        expected_keys = {
            "name",
            "content",
            "fragment_label",
            "query",
            "fuzzy_score",
            "context_score",
        }
        assert set(matches[0]) == expected_keys


