class TestSaveModeRouting:
    """Queries starting with 'new' must divert to save mode, not search."""

    @pytest.fixture(autouse=True)
    def spy_save_mode(self, monkeypatch):
        calls = []

        def fake_handle(self, query, extension):
            calls.append(query)
            return "SAVE_MODE_RESULT"

        monkeypatch.setattr(KeywordQueryEventListener, "_handle_save_mode", fake_handle)
        self.calls = calls

    def _run(self, listener, argument):
        return listener.on_event(FakeKeywordQueryEvent(argument), make_extension())

    def test_bare_new_routes_to_save(self, listener):
        assert self._run(listener, "new") == "SAVE_MODE_RESULT"

    def test_new_with_name_routes_to_save(self, listener):
        self._run(listener, "new my snippet name")

        assert self.calls == ["new my snippet name"]

    def test_case_insensitive(self, listener):
        self._run(listener, "NEW")

        assert len(self.calls) == 1

    def test_leading_whitespace_still_matches(self, listener):
        self._run(listener, "   new  ")

        assert len(self.calls) == 1

    def test_search_containing_new_elsewhere_not_diverted(self, listener, monkeypatch):
        # 'renewable energy' contains 'new' but doesn't start with it
        monkeypatch.setattr(
            SnippetCache,
            "get_snippets",
            classmethod(lambda cls, **kw: []),
        )
        result = self._run(listener, "renewable")

        assert result != "SAVE_MODE_RESULT"


